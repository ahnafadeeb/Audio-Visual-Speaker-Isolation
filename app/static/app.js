// Deep link: /?job=demo skips the upload entirely and loads an existing job.
// This is how scripts/make_demo_job.py hands the walking skeleton to the UI,
// and how you recover a finished job after restarting the server.
(async function boot() {
  const jobId = new URLSearchParams(location.search).get('job');
  if (!jobId) return;
  try {
    const res = await fetch(`/api/jobs/${jobId}`);
    if (!res.ok) { showError(`job "${jobId}" not found`); return; }
    const s = await res.json();
    if (s.state !== 'done') { el.panelUpload.hidden = true; listen(jobId); return; }
    el.panelUpload.hidden = true;
    await load(jobId, s.meta);
  } catch (err) {
    // This is the presentation path: /?job=demo, opened cold. An unhandled
    // rejection here leaves an empty page with the upload panel hidden.
    toUpload(`could not open job "${jobId}": ${err.message}`);
  }
})();
