document.addEventListener('keydown', (e) => {
  if (el.panelPlayer.hidden) return;
  // Never steal a browser or OS shortcut: Ctrl+1 switches tabs, Alt+Left goes
  // back. Without this, both also flip the speaker or scrub the clip.
  if (e.ctrlKey || e.metaKey || e.altKey) return;
  if (e.code === 'Space') {
    e.preventDefault();
    if (!e.repeat) transport.toggle();   // holding space must not re-toggle
    return;
  }
  if (e.code === 'ArrowLeft')  transport.seek(engine.position() - 5);
  if (e.code === 'ArrowRight') transport.seek(engine.position() + 5);
  // Layout-independent, and `e.key` for a letter cannot collide with the digit
  // branch below (parseInt('s') is NaN). The repeat guard matters more here than
  // for Space: holding the key would walk the whole cycle of pairings and stop
  // somewhere arbitrary.
  if (e.key && e.key.toLowerCase() === 's') {
    if (!e.repeat) ui.nextPairing();
    return;
  }
  if (e.key && e.key.toLowerCase() === 'n') {
    if (!e.repeat) newVideo();
    return;
  }
  if (e.key && e.key.toLowerCase() === 'i') {
    if (!e.repeat) ui.toggleMode();
    return;
  }
  // The digits select the nth SPEAKER BUTTON, i.e. the nth face in the order
  // they are drawn — not the nth channel. Those two orders coincide only while
  // `channel_of` is the identity, which it is as the test clip ships, so a
  // channel-indexed shortcut looks fine there. It stops being fine in two
  // reachable states: an unmatched face leaves a hole (`[0, null, 1]`, where "3"
  // must reach channel 1, not the column 2 the wav does not have), and pressing
  // Swap makes the channel order user-mutable — which on this clip the user MUST
  // do, since the shipped pairing is inverted. A channel-indexed shortcut would
  // then change meaning under their hands.
  const d = parseInt(e.key, 10);
  if (d >= 1 && d <= 9) ui.selectTrack(d - 1);
});

