// --------------------------------------------------------------------------
// Audio engine
// --------------------------------------------------------------------------

const engine = {
  ctx: null, buffer: null, source: null,
  splitter: null, gains: [], analysers: [], master: null,
  active: 0, playing: false,
  anchorCtxTime: 0, anchorOffset: 0, pausedAt: 0,
  resampled: false, _lvlBuf: null,

  async init(stemsUrl) {
    // 16 kHz context: decodeAudioData resamples to the context rate, so a
    // default 48 kHz context would upsample every stem 3x — tripling memory
    // and altering the very samples the DSP chain worked to zero.
    //
    // That second clause is the load-bearing one. The gate's guarantee is
    // BIT-EXACT zeros in the muted regions; a resampler is a windowed sinc, so
    // it drags energy from the nonzero samples on either side of a gated pause
    // straight into the middle of it. Matching the context rate to the file
    // rate is what makes decodeAudioData a copy instead of a filter.
    if (!this.ctx) {
      const Ctor = window.AudioContext || window.webkitAudioContext;
      try {
        this.ctx = new Ctor({ sampleRate: 16000 });
      } catch (_) {
        // Not every implementation honours an explicit rate. Running at the
        // device rate is far better than not running, but it is no longer the
        // bit-exact path, so say so rather than quietly weakening the claim.
        this.ctx = new Ctor();
        this.resampled = this.ctx.sampleRate !== 16000;
      }
    }
    // init() runs again whenever a job is loaded into a live page — the
    // error-then-retry path does exactly that. Without a teardown the previous
    // graph stays wired to destination: the old source keeps playing UNDER the
    // new one, on gains nothing can reach any more, so no click can silence it.
    this.reset();

    const bytes = await (await fetch(stemsUrl)).arrayBuffer();
    this.buffer = await this.ctx.decodeAudioData(bytes);

    const n = this.buffer.numberOfChannels;      // read it, never assume
    this.master = this.ctx.createGain();
    this.master.connect(this.ctx.destination);
    this.splitter = this.ctx.createChannelSplitter(n);

    this.gains = [];
    this.analysers = [];
    for (let i = 0; i < n; i++) {
      const g = this.ctx.createGain();
      g.gain.value = (i === this.active) ? 1 : 0;
      this.splitter.connect(g, i, 0);            // connect(dest, outputIdx, inputIdx)

      // Meter taps POST-gain, so a muted speaker's meter reads exactly zero.
      // That is the demo: you can see the silence, not just fail to hear it.
      const a = this.ctx.createAnalyser();
      a.fftSize = 1024;
      g.connect(a);
      g.connect(this.master);

      this.gains.push(g);
      this.analysers.push(a);
    }
    return n;
  },

  /* Tear the graph down to nothing. Every disconnect is guarded because a node
   * that was never connected throws, and a half-completed teardown is worse
   * than none: it leaves audible nodes with no handle left to silence them. */
  reset() {
    this.stopSource();
    for (const g of this.gains) { try { g.disconnect(); } catch (_) {} }
    for (const a of this.analysers) { try { a.disconnect(); } catch (_) {} }
    if (this.splitter) { try { this.splitter.disconnect(); } catch (_) {} }
    if (this.master) { try { this.master.disconnect(); } catch (_) {} }
    this.splitter = null;
    this.master = null;
    this.gains = [];
    this.analysers = [];
    this._lvlBuf = null;
    this.playing = false;
    this.pausedAt = 0;
    this.active = 0;
  },

  get duration() { return this.buffer ? this.buffer.duration : 0; },

  position() {
    if (!this.playing || !this.ctx) return this.pausedAt;
    const ts = this.ctx.getOutputTimestamp ? this.ctx.getOutputTimestamp() : null;
    // contextTime reports the frame ACTUALLY being played; ctx.currentTime runs
    // ahead by baseLatency + outputLatency.
    const now = (ts && typeof ts.contextTime === 'number') ? ts.contextTime : this.ctx.currentTime;
    // Clamp the ELAPSED term at zero, not the sum. play() schedules the source
    // 80 ms in the future, so for those 80 ms `now - anchorCtxTime` is negative
    // and the old form reported a position 80 ms BEFORE the true start — while
    // the video was already rolling. The corrector saw a phantom 80 ms of drift
    // and started braking the video at the top of every play.
    const elapsed = Math.max(0, now - this.anchorCtxTime);
    return Math.min(this.duration, Math.max(0, this.anchorOffset + elapsed));
  },

  async play(offset) {
    if (this.ctx.state === 'suspended') await this.ctx.resume();
    this.stopSource();
    const at = (offset !== undefined) ? offset : this.pausedAt;

    const src = this.ctx.createBufferSource();
    src.buffer = this.buffer;
    src.connect(this.splitter);
    const t0 = this.ctx.currentTime + 0.08;      // scheduling cushion
    const startAt = Math.min(at, Math.max(0, this.duration - 0.01));
    src.start(t0, startAt);
    // The context time at which the buffer runs out on its own.
    const endsAt = t0 + (this.duration - startAt);
    // Compare against `this.source`, not just `this.playing`: a seek stops the
    // old source and starts a new one, and Chrome fires the stopped source's
    // onended asynchronously AFTER the new one is running. Without the identity
    // check that stale event ends playback a beat after every backward seek.
    //
    // The second guard is deliberately NOT position(). That reads
    // getOutputTimestamp().contextTime — the frame leaving the speakers, which
    // lags ctx.currentTime by baseLatency + outputLatency: routinely 100-200 ms
    // under shared-mode WASAPI on Windows. So at the instant the buffer runs
    // out, position() is still that far short of duration, and the old
    // `position() >= duration - 0.05` could never be satisfied on such a
    // machine. onEnded() was never called: the button stayed stuck reading
    // "Pause" at the end of every clip and had to be pressed twice to restart.
    //
    // ctx.currentTime is the RENDERING clock — the same one src.start() is
    // scheduled against — so comparing it to the scheduled end is exact no
    // matter how deep the output buffer is. scripts/check_transport.py pins
    // both halves: the old guard passes below ~50 ms of output latency (which
    // is why it looked fine in development) and never fires above it.
    src.onended = () => {
      if (this.source === src && this.playing
          && this.ctx.currentTime >= endsAt - 0.05) transport.onEnded();
    };

    this.source = src;
    this.anchorCtxTime = t0;
    this.anchorOffset = at;
    this.playing = true;
  },

  pause() {
    this.pausedAt = this.position();
    this.stopSource();
    this.playing = false;
  },

  stopSource() {
    if (this.source) {
      try { this.source.onended = null; this.source.stop(); } catch (_) {}
      try { this.source.disconnect(); } catch (_) {}
      this.source = null;
    }
  },

  /* Instant, click-free speaker switch. */
  select(k) {
    // A track with no matched stem has channel === null. Selecting it would
    // set every gain to 0 (i === k never true) and silence the whole app, so
    // refuse the switch and leave the current speaker playing.
    if (!this.gains.length || k === null || k === undefined || !this.gains[k]) return;
    this.active = k;
    // SCHED_LEAD (20 ms) ahead of currentTime, not 5 ms: the rendering quantum
    // at 16 kHz is 8 ms, and a lead that lands inside the block already being
    // rendered snaps the event to that block's head, truncating the crossfade.
    const t = this.ctx.currentTime + SCHED_LEAD;
    try {
      this.gains.forEach((g, i) => {
        // cancelScheduledValues + setValueAtTime FIRST: overlapping
        // setValueCurveAtTime events on one param throw, which a fast
        // double-click on two faces would otherwise trigger mid-playback.
        g.gain.cancelScheduledValues(t);
        g.gain.setValueAtTime(g.gain.value, t);
        g.gain.setValueCurveAtTime(i === k ? UP : DOWN, t, XFADE);
        // The curve ends at cos(pi/2) ≈ 6.1e-17 (−324 dB). Pin it to bit-exact
        // zero so "absolute silence" is literally true.
        g.gain.setValueAtTime(i === k ? 1 : 0, t + XFADE + 0.001);
      });
    } catch (_) {
      // The ordering above is the defence, but it rests on the spec clause that
      // cancelScheduledValues() removes a setValueCurveAtTime whose window
      // contains cancelTime — and implementations have disagreed about that.
      // If it throws, it throws PART WAY THROUGH the forEach: the incoming gain
      // may already be scheduled to 1 while the outgoing one was never taken
      // down. Both speakers audible at once is the precise failure this whole
      // project exists to prevent, and it would be reachable by double-clicking
      // two faces. So: abandon the crossfade, keep the invariant. A 25 ms click
      // is a fair price for never bleeding.
      this.hardSet(k);
    }
    ui.markActive(k);
  },

  /* Last-resort switch: exactly one gain at 1, every other at bit-exact 0,
   * immediately and with no automation left on the timeline to undo it. */
  hardSet(k) {
    const now = this.ctx.currentTime;
    this.gains.forEach((g, i) => {
      const target = (i === k) ? 1 : 0;
      // cancelScheduledValues(0) clears the ENTIRE timeline, including the
      // partially-applied events that just threw. A scoped cancel would leave
      // one of them to fire and re-open the channel we are closing.
      try { g.gain.cancelScheduledValues(0); } catch (_) {}
      try { g.gain.setValueAtTime(target, now); } catch (_) { g.gain.value = target; }
    });
  },

  levels() {
    // Hoisted buffers. This runs on every animation frame for the life of the
    // page; a fresh Float32Array(1024) per analyser per frame is ~0.5 MB/s of
    // garbage, and the minor GC it eventually forces lands as a dropped frame
    // in the middle of the demo.
    if (!this._lvlBuf || this._lvlBuf.length !== this.analysers.length) {
      this._lvlBuf = this.analysers.map((a) => new Float32Array(a.fftSize));
    }
    return this.analysers.map((a, i) => {
      const buf = this._lvlBuf[i];
      a.getFloatTimeDomainData(buf);
      let sum = 0;
      for (let j = 0; j < buf.length; j++) sum += buf[j] * buf[j];
      return Math.sqrt(sum / buf.length);
    });
  },
};

// --------------------------------------------------------------------------
// Transport + A/V drift correction
// --------------------------------------------------------------------------

const transport = {
  gen: 0,           // generation token: only the newest loop chain survives
  busy: false,      // toggle() re-entrancy guard

  /* The systematic lag that frame quantisation alone accounts for, in seconds.
   *
   * rVFC reports mediaTime for the frame ACTUALLY on screen, and a frame is on
   * screen at a frame boundary or not at all. So mediaTime is the true media
   * position floored to 1/fps: with the clocks in perfect agreement it lags the
   * audio by 0..1/fps, averaging half a frame period. That is a known offset,
   * not error, so it is SUBTRACTED before the drift is judged — rather than
   * hidden by widening the deadband, which would spend the whole allowance on
   * one direction and leave real audio-ahead error untested (the one-sidedness
   * is why; scripts/check_transport.py fails the symmetric-band version).
   *
   * Half a frame period is the expected value of a uniform sweep, so debiasing
   * by it leaves a residual of ±1/(2·fps) — ±20 ms at 25 fps, inside DEADBAND.
   */
  quantBias() {
    const fps = (ui.fps > 0) ? ui.fps : 25;
    return 0.5 / fps;
  },

  async toggle() {
    // toggle() awaits ctx.resume() and video.play(), so a second space-bar
    // press lands mid-flight while engine.playing is still false. Without the
    // guard that second call runs engine.play() again, whose stopSource()
    // kills the source the first call just started.
    if (this.busy) return;
    this.busy = true;
    try {
      if (engine.playing) {
        engine.pause();
        el.video.pause();
        el.playpause.textContent = 'Play';
        this.gen++;                       // retire the running chain now
        ui.updateTime(engine.pausedAt);
      } else {
        await engine.play();
        el.video.currentTime = engine.pausedAt;
        await el.video.play().catch(() => {});
        el.playpause.textContent = 'Pause';
        this.loop();
      }
    } finally {
      this.busy = false;
    }
  },

  onEnded() {
    engine.playing = false;
    engine.pausedAt = 0;
    this.gen++;
    el.video.pause();
    el.playpause.textContent = 'Play';
    ui.updateTime(0);
  },

  seek(t) {
    const was = engine.playing;
    engine.pausedAt = Math.max(0, Math.min(engine.duration, t));
    el.video.currentTime = engine.pausedAt;
    if (was) {
      engine.play(engine.pausedAt);
    } else {
      // Paused, nothing repaints on its own: draw() and updateTime() are only
      // ever called from the correction loop, and the loop only runs during
      // playback. Arrow-key scrubbing while paused moved the video but left the
      // boxes and the clock on the frame we seeked away from — so the box you
      // see is not the box hitTest() will match, and clicking a face does
      // nothing. Repaint explicitly.
      ui.draw(engine.pausedAt);
      ui.updateTime(engine.pausedAt);
    }
  },

  loop() {
    // ONE chain, ever.
    //
    // toggle() starts a chain and the visibilitychange handler starts another,
    // and a chain's only exit was `!engine.playing` — which is false for as
    // long as it matters. So every tab-away-and-back while playing added a
    // permanent extra chain: N copies of the same P-controller each writing
    // el.video.playbackRate, N canvas redraws per frame, and — worst — N
    // independent hard reseeks, each of which invalidates the mediaTime the
    // others are still reasoning about. The trigger and the damage coincide:
    // returning to the tab is exactly when drift is large enough to reseek.
    //
    // A generation token retires every older chain on its next tick, so it does
    // not matter how many callers ask for a loop or how often.
    const me = ++this.gen;
    const alive = () => engine.playing && me === this.gen;

    if (!('requestVideoFrameCallback' in el.video)) {
      // Fallback for browsers without rVFC: coarser, but keeps A/V together.
      const tick = () => {
        if (!alive()) return;
        this.correct(el.video.currentTime);
        ui.draw(el.video.currentTime);
        requestAnimationFrame(tick);
      };
      requestAnimationFrame(tick);
      return;
    }
    const onFrame = (_now, meta) => {
      if (!alive()) return;
      this.correct(meta.mediaTime);
      ui.draw(meta.mediaTime);       // mediaTime is the frame ON SCREEN, so the
      el.video.requestVideoFrameCallback(onFrame);   // box cannot lag the face
    };
    el.video.requestVideoFrameCallback(onFrame);
  },

  /* The video chases the audio. Never the reverse: nudging audio playbackRate
   * resamples without pitch correction and is audible. Video rate changes are
   * silent because the element is muted. */
  correct(mediaTime) {
    const audioPos = engine.position();
    // Remove the known quantisation offset first (mediaTime is floored to a
    // frame boundary, so a synced video reports -1/fps..0, not 0), then judge
    // and display the residual. Displaying the RAW drift to the user is wrong
    // on both counts: a synced clip reads a steady "negative frame period",
    // and the warn state, steered by the same raw value, would sit there.
    const drift = (mediaTime - audioPos) + this.quantBias();

    if (Math.abs(drift) > HARD_SEEK) {
      // A seek is not instant. While it runs, mediaTime keeps reporting the
      // pre-seek frame, so the next callbacks compute the same large drift and
      // fire the same seek again — each one cancelling the last, which is how
      // a single large drift turns into a seek storm that never converges.
      if (!el.video.seeking) {
        el.video.currentTime = audioPos;
        el.video.playbackRate = 1;
      }
    } else if (Math.abs(drift) > DEADBAND) {
      // Steer at the drift BEYOND the deadband, not the raw drift. Using the
      // raw value means the controller is still commanding a correction of
      // KP*DEADBAND at the moment it stops caring, so it overshoots to the far
      // edge of the band and gets called straight back — a limit cycle that
      // keeps playbackRate permanently off 1 and the readout flickering.
      const excess = drift - Math.sign(drift) * DEADBAND;
      const adj = Math.max(-MAX_RATE, Math.min(MAX_RATE, -KP * excess));
      el.video.playbackRate = 1 + adj;
    } else {
      el.video.playbackRate = 1;
    }

    if (el.showDrift.checked) {
      el.drift.textContent = `${(drift * 1000).toFixed(0)} ms`;
      el.drift.className = 'drift ' + (Math.abs(drift) > DEADBAND ? 'warn' : 'ok');
    } else if (el.drift.textContent) {
      el.drift.textContent = '';     // otherwise the last reading sits there
      el.drift.className = 'drift';  // forever, next to an unchecked box
    }
    ui.updateTime(audioPos);
  },
};

// rAF and rVFC do not fire in a hidden tab, so the corrector freezes while
// backgrounded. AudioContext keeps running, so on return the gap can be
// seconds — far past what a ±2% corrector could crawl back. Reseek once.
// loop() is safe to call again here: it retires the chain it replaces.
document.addEventListener('visibilitychange', () => {
  if (!document.hidden && engine.playing) {
    el.video.currentTime = engine.position();
    el.video.playbackRate = 1;
    transport.loop();
  }
});

