/* Next permutation of `a` in lexicographic order, in place. Returns false when
 * `a` was already the last one, having wrapped it back to sorted order.
 *
 * Standard algorithm, O(n) and allocation-free. Stepping one press at a time is
 * what makes the pairing control COMPLETE: lexicographic stepping with wrap is a
 * single cycle over all n! orders, so every pairing is reachable and n! presses
 * return to the one you started from. A cyclic rotation would be shorter, and
 * for two speakers identical, but with three faces it reaches only 3 of the 6
 * pairings — so if the pipeline transposed exactly two of them, the user could
 * never fix it with any number of presses. */
function nextPermutation(a) {
  let i = a.length - 2;
  while (i >= 0 && a[i] >= a[i + 1]) i--;
  if (i < 0) { a.reverse(); return false; }
  let j = a.length - 1;
  while (a[j] <= a[i]) j--;
  const t = a[i]; a[i] = a[j]; a[j] = t;
  for (let l = i + 1, r = a.length - 1; l < r; l++, r--) {
    const u = a[l]; a[l] = a[r]; a[r] = u;
  }
  return true;
}

const ui = {
  tracks: null, fps: 25, meta: null,
  modes: null,       // tracks.json `modes`: version name -> channel offset
  mode: null,        // the version playing now
  adapter: null,     // tracks.json `adapter`: fine-tuned model name, null = released weights
  adapterFaces: null, // per face: did the adapter run on it (it only knows its own people)
  lastIdx: 0,        // the frame index actually drawn — hitTest must reuse it
  meterGen: 0,       // generation token, same reason as transport.gen
  pairing: null,     // tracks.json's own verdict on whether the labels are safe
  baseChans: null,   // the stem→face binding the pipeline shipped
  steps: 0,          // how many times the user has stepped it

  setTracks(data, meta) {
    this.tracks = data.tracks;
    this.fps = data.fps || 25;
    this.meta = meta;
    // Shipped in tracks.json alongside the boxes, deliberately, so the browser
    // knows in the SAME payload whether the channel labels can be trusted.
    // Absent on jobs produced before that block existed — treat as unknown, not
    // as trustworthy.
    this.pairing = data.pairing || null;
    // Snapshot before anything can permute it: nextPairing() mutates t.channel,
    // so the pipeline's own answer has to be kept somewhere to report against.
    this.baseChans = this.tracks.map((t) => t.channel);
    this.steps = 0;
    // Strict first: it is the version that answers "only this voice".
    this.modes = data.modes || null;
    this.adapter = data.adapter || null;
    this.adapterFaces = data.adapter_faces || null;
    this.mode = this.modes ? ('strict' in this.modes ? 'strict' : Object.keys(this.modes)[0]) : null;

    this.renderSpeakers();
    this.renderPairing();
    this.renderMode();
  },

  /* Rebuild the speaker buttons from `this.tracks`. Separate from setTracks()
   * because rotate() has to redraw them against a changed channel binding, and
   * because a rebuild is the only way to keep `dataset.channel` — which
   * meters() indexes by — from going stale. */
  renderSpeakers() {
    el.speakers.innerHTML = '';
    this.tracks.forEach((t, i) => {
      // channel === null means the matcher found this face but had no stem to
      // give it. Show it, so the detection is visible, but do not let it be
      // selected — there is nothing to switch to.
      const unmatched = t.channel === null || t.channel === undefined;
      const b = document.createElement('button');
      b.className = 'speaker' + (unmatched ? ' unmatched' : '');
      if (!unmatched) b.dataset.channel = t.channel;
      b.disabled = unmatched;
      b.innerHTML =
        `<span class="sw-name">${esc(t.label)}</span>` +
        `<span class="meter"><i></i></span>` +
        // The caveat text names the actual cause ("on screen 13% of the clip")
        // rather than the generic "low confidence" this used to show, because
        // the causes call for different responses and only one of them is
        // something the user can act on. Older jobs have no `caveat` field, so
        // the generic string stays as the fallback.
        (unmatched
          ? '<span class="warn-tag" title="detected, but no separated stem was assigned">no stem</span>'
          : t.reliable ? ''
          : `<span class="warn-tag" title="${esc(t.caveat || 'weak audio-visual correlation')}">${esc(t.caveat || 'low confidence')}</span>`);
      // Read the channel through `this.tracks[i]` at CLICK time, not through the
      // `t` captured now: rotate() rebinds it, and a closure over the old value
      // would keep selecting the stem this face used to own.
      if (!unmatched) b.onclick = () => this.selectTrack(i);
      el.speakers.appendChild(b);
    });
    this.markActive(engine.active);
  },

  /* Every path that selects a speaker goes through here, in TRACK space. The
   * user points at a face; which channel that face currently owns is a lookup,
   * not an identity — that distinction is the whole subject of channels.py and
   * it does not stop being true on this side of the wire. */
  selectTrack(i) {
    const t = this.tracks && this.tracks[i];
    if (!t) return;
    engine.select(t.channel + this.offset());
  },

  /* Where the current isolation version starts in the channel list. The AV
   * path ships every version in ONE buffer -- strict in [0, N), natural in
   * [N, 2N) -- so switching version is the same crossfade as switching
   * speaker and cannot drift. `t.channel` stays the face's index within a
   * version; every face->channel lookup adds this. Old jobs have no `modes`
   * and the offset is 0. */
  offset() {
    return (this.modes && this.mode && this.modes[this.mode]) || 0;
  },

  /* The face whose audio is playing now, or undefined. */
  selectedTrack() {
    if (!this.tracks) return undefined;
    const off = this.offset();
    const i = this.tracks.findIndex(
      (t) => t.channel !== null && t.channel !== undefined && t.channel + off === engine.active);
    return i < 0 ? undefined : i;
  },

  /* Strict <-> natural, keeping the same face selected and playback running. */
  toggleMode() {
    if (!this.modes) return;
    const sel = this.selectedTrack();
    const names = Object.keys(this.modes);
    this.mode = names[(names.indexOf(this.mode) + 1) % names.length];
    if (sel !== undefined) this.selectTrack(sel);
    this.renderMode();
    this.writeDiag();
    this.repaint();
  },

  renderMode() {
    if (!el.mode) return;
    el.mode.hidden = !this.modes;
    if (!this.modes) return;
    const strict = this.mode === 'strict';
    el.mode.textContent = strict ? 'Isolation: strict' : 'Isolation: natural';
    el.mode.classList.toggle('on', strict);
    el.mode.title = strict
      ? 'Strict: the other voices are removed as far as possible; the selected voice can sound slightly processed. (I) for natural.'
      : 'Natural: the selected voice is untouched by extra filtering; the other voices can be faintly audible. (I) for strict.';
  },

  /* Step the stem→face binding to the next pairing, without touching the
   * transport.
   *
   * With two speakers there are two pairings, so one press always fixes an
   * inverted one. With three or more, repeated presses walk every pairing in
   * turn and come back to where they started, so the control can neither strand
   * the user nor fail to express the fix they need.
   *
   * `t.channel` is mutated in place rather than shadowed by a parallel lookup
   * table, because draw(), hitTest() and meters() all read it. A second source
   * of truth would leave three of them reading the stale one. */
  nextPairing() {
    if (!this.tracks) return false;
    const idx = this.tracks
      .map((t, i) => i)
      .filter((i) => {
        const c = this.tracks[i].channel;
        return c !== null && c !== undefined;
      });
    if (idx.length < 2) return false;          // nothing to permute

    // Which FACE is selected, resolved BEFORE the rebinding. The point of the
    // control is that the same face stays selected and the audio behind it
    // changes; carrying the selection as a channel would keep the same audio
    // and move the highlight, which is the opposite.
    const sel = idx.find((i) => this.tracks[i].channel + this.offset() === engine.active);
    const chans = idx.map((i) => this.tracks[i].channel);
    nextPermutation(chans);
    idx.forEach((i, k) => { this.tracks[i].channel = chans[k]; });
    this.steps++;

    this.renderSpeakers();
    // Through engine.select(), so the 25 ms crossfade runs and the clip keeps
    // playing: switching audio must never interrupt playback.
    if (sel !== undefined) this.selectTrack(sel);
    this.renderPairing();
    this.writeDiag();
    this.repaint();
    return true;
  },

  /* True when the binding on screen is no longer the one the pipeline shipped.
   * Compared against the stored base rather than inferred from a step counter,
   * because lexicographic stepping wraps through sorted order rather than
   * through the pipeline's pairing, and n! arithmetic would be one more thing
   * to get wrong for no benefit. */
  overridden() {
    if (!this.tracks || !this.baseChans) return false;
    return this.tracks.some((t, i) => t.channel !== this.baseChans[i]);
  },

  /* The swap row: visible whenever there is something to permute, with a note
   * only when the pairing is known to be untrustworthy. Stating a p-value the
   * user can act on beats a silent wrong answer, which is what shipped before. */
  renderPairing() {
    // Guarded, and so is the onclick below: a browser holding a cached
    // index.html from before this row existed would otherwise take an exception
    // in top-level script and lose the ENTIRE app, not just the swap button.
    if (!el.pairing || !el.swap || !el.pairingNote) return;
    const matched = this.tracks
      ? this.tracks.filter((t) => t.channel !== null && t.channel !== undefined).length
      : 0;
    el.pairing.hidden = matched < 2;
    if (matched < 2) return;

    const p = this.pairing;
    const suspect = p && p.trustworthy === false;
    const changed = this.overridden();
    el.swap.textContent = matched === 2 ? 'Swap audio' : 'Next pairing';
    el.swap.classList.toggle('urgent', !!suspect && !changed);
    el.swap.title = matched === 2
      ? 'Swap which voice each face is bound to (S). Playback does not stop.'
      : `Step through the ${matched} faces' voice assignments (S). ` +
        'Playback does not stop.';

    let note = '';
    if (suspect) {
      const sig = typeof p.significance === 'number'
        ? ` (p = ${p.significance.toFixed(2)}: ${Math.round(p.significance * 100)}% of ` +
          `time-shifted controls score as well)`
        : '';
      note = `The audio-visual pairing on this clip is not distinguishable from chance${sig}. ` +
             (matched === 2 ? 'If the voices are on the wrong faces, one press fixes it.'
                            : 'Press until the voices land on the right faces.');
    } else if (p && p.trustworthy === true) {
      // Phrased from `basis`, because the two paths earn the same verdict in
      // incompatible ways and only one of them ran a null test. Saying
      // "verified against a time-shifted null" on an AV-TSE job would be
      // describing a statistic nobody computed.
      note = p.basis === 'conditioning'
        ? 'Each voice was extracted from that face’s own lip motion, so the ' +
          'pairing is given, not inferred. Swap anyway if it sounds wrong.'
        : 'Pairing verified against a time-shifted null. Swap anyway if it sounds wrong.';
    }
    if (changed) {
      note += `${note ? ' ' : ''}Overridden by hand (${this.steps} ` +
              `press${this.steps === 1 ? '' : 'es'}); the pipeline's own pairing ` +
              `was ${JSON.stringify(this.baseChans)}.`;
    }
    el.pairingNote.textContent = note;
  },

  markActive(k) {
    const off = this.offset();
    [...el.speakers.children].forEach((b) => {
      b.classList.toggle('active',
        b.dataset.channel !== undefined && Number(b.dataset.channel) + off === k);
    });
  },

  draw(mediaTime) {
    const cv = el.overlay, v = el.video;
    const w = v.clientWidth, h = v.clientHeight;
    if (!w || !h) return;
    // Size the backing store in DEVICE pixels and scale the context, rather
    // than in CSS pixels. The canvas is stretched to the element box by CSS
    // either way, so the geometry was already right — but a 1x store on a 2x
    // laptop panel is upscaled by the compositor, and the 2px box strokes and
    // 12px labels come out visibly soft on the one screen the demo runs on.
    const dpr = Math.min(MAX_DPR, window.devicePixelRatio || 1);
    const bw = Math.round(w * dpr), bh = Math.round(h * dpr);
    if (cv.width !== bw || cv.height !== bh) { cv.width = bw; cv.height = bh; }

    const g = cv.getContext('2d');
    g.setTransform(dpr, 0, 0, dpr, 0, 0);      // draw in CSS-pixel coordinates
    g.clearRect(0, 0, w, h);
    if (!this.tracks) return;

    const idx = Math.round(mediaTime * this.fps);
    // Remember what was actually drawn. hitTest() used to recompute the index
    // from engine.position(), i.e. the AUDIO clock, while this runs on the
    // VIDEO clock — and the two are only guaranteed to agree within HARD_SEEK,
    // 250 ms, which at 25 fps is six frames of head movement. The user clicks
    // the box they can see; matching against a box from a different frame is
    // how a click on a face silently selects the wrong speaker, or nothing.
    this.lastIdx = idx;
    this.tracks.forEach((t) => {
      const box = t.boxes[idx];
      if (!box) return;                       // null is a real state: no face.
      const [x, y, bw2, bh2] = box;           // Interpolating across it would
      const matched = t.channel !== null && t.channel !== undefined;
      const active = matched && t.channel + this.offset() === engine.active;
      g.lineWidth = active ? 3 : 2;                            // never on screen
      g.strokeStyle = active ? '#4ade80'
                    : matched ? 'rgba(255,255,255,.45)'
                    : 'rgba(251,191,36,.5)';   // amber: seen, but no stem
      if (!matched) g.setLineDash([5, 4]);
      g.strokeRect(x * w, y * h, bw2 * w, bh2 * h);
      g.setLineDash([]);

      g.font = '600 12px system-ui, sans-serif';
      const label = t.label;
      const tw = g.measureText(label).width + 12;
      g.fillStyle = active ? '#4ade80' : 'rgba(0,0,0,.55)';
      g.fillRect(x * w, y * h - 20, tw, 18);
      g.fillStyle = active ? '#04210f' : '#fff';
      g.fillText(label, x * w + 6, y * h - 7);
    });
  },

  /* Repaint at the current position without advancing anything. Needed
   * wherever the geometry can change while the correction loop is NOT running:
   * a window resize, or the <video> element resizing itself the moment its
   * metadata arrives. Before metadata a <video> has no intrinsic ratio, so
   * `height: auto` resolves to the CSS default 150 px — the first draw(0) in
   * load() paints into a box the wrong shape, and while paused nothing ever
   * repaints it. */
  repaint() {
    if (!this.tracks) return;
    this.draw(engine.playing ? engine.position() : engine.pausedAt);
  },

  hitTest(ev) {
    if (!this.tracks) return;
    const r = el.video.getBoundingClientRect();
    const u = (ev.clientX - r.left) / r.width;    // normalised space: no pixel
    const vv = (ev.clientY - r.top) / r.height;   // maths, no resize handler
    // The frame that is ON SCREEN, not the one the audio clock implies.
    const idx = this.lastIdx;
    for (let i = 0; i < this.tracks.length; i++) {
      const t = this.tracks[i];
      const b = t.boxes[idx];
      if (!b || t.channel === null || t.channel === undefined) continue;
      if (u >= b[0] && u <= b[0] + b[2] && vv >= b[1] && vv <= b[1] + b[3]) {
        this.selectTrack(i);
        return;
      }
    }
  },

  updateTime(pos) {
    el.time.textContent = `${fmt(pos)} / ${fmt(engine.duration)}`;
  },

  /* The diagnostics block. A method rather than a one-shot write in load(),
   * because the stem→face binding is now user-mutable and a panel that still
   * showed the pipeline's original pairing after a swap would be reporting
   * something that is no longer true. */
  writeDiag() {
    const meta = this.meta;
    // `null` here is not missing data: the server sends it for a measurement
    // that does not exist — a channel with no nonzero sample has no residual
    // floor, and a channel whose rival never holds the floor alone has no
    // whisper window. Say so, rather than printing a bare `null` that reads
    // like a bug.
    const nd = (v) => (v === null || v === undefined ? 'n/a (no measurement window)'
                                                    : v);
    // whisper_db replaced leakage_db: the old key was computed by handing the
    // leakage metric the neighbouring OUTPUT channel instead of a ground-truth
    // interferer, which made it RISE as separation improved. Jobs produced
    // before that fix still carry the stale key; show nothing rather than a
    // number that means the opposite of what the label claims.
    const whisper = (meta && meta.silence && meta.silence.whisper_db) || null;
    el.diagBody.textContent = JSON.stringify({
      channels: engine.gains.length,
      isolation: this.modes ? `${this.mode} (channel offset ${this.offset()})` : 'single version',
      separator: meta && meta.separator,
      model: this.adapter
        ? `adapter "${this.adapter}" on ${this.tracks.filter((t, i) => this.adapterFaces && this.adapterFaces[i]).map((t) => t.label).join(', ') || 'no face'}; released weights for the rest`
        : 'released weights',
      device: meta && meta.device,
      vision_backend: meta && meta.vision_backend,
      elapsed_s: meta && meta.elapsed_s,
      // Which stem each face is bound to RIGHT NOW, plus how far that is from
      // what the pipeline shipped. The demo's most likely failure is an
      // inverted pairing, so the state of the fix belongs where it can be read.
      channel_map: this.tracks
        ? Object.fromEntries(this.tracks.map(
            (t) => [t.label, t.channel === null || t.channel === undefined
              ? 'no stem' : t.channel]))
        : null,
      user_rotations: this.steps,
      pipeline_channel_map: this.baseChans,
      pairing: this.pairing || 'n/a (job predates this block)',
      // Per channel, and lower is better: how loud the ghost is in the channel
      // you selected, relative to that channel's own speech.
      whisper_db: whisper
        ? Object.fromEntries(Object.entries(whisper).map(([k, v]) => [k, nd(v)]))
        : 'n/a (job predates this metric)',
      context_rate: engine.ctx ? engine.ctx.sampleRate : null,
      // Surfaced because it changes what the numbers above mean: if the browser
      // would not give us a 16 kHz context, decodeAudioData resampled the stems
      // and the exact zeros measured server-side are no longer exact in the
      // buffer being played.
      bit_exact_playback: !engine.resampled,
      silence: meta && meta.silence,
    }, (k, v) => (k === 'nonzero_floor_db' && v === null ? 'none (perfect silence)' : v), 2);
  },

  meters() {
    const me = ++this.meterGen;
    const tick = () => {
      // Retire on generation change, and stop entirely once the player panel is
      // gone. The old version recursed unconditionally forever: load a second
      // job and two loops run, both walking the DOM and reading every analyser
      // on every frame, for the rest of the page's life.
      if (me !== this.meterGen || el.panelPlayer.hidden) return;
      const levels = engine.levels();
      // Index by dataset.channel, NOT by position. el.speakers.children has one
      // button per TRACK, including unmatched ones (channel === null); levels[]
      // has one entry per CHANNEL. The two lists diverge the moment a face is
      // detected without a stem — every later button then reads its neighbour's
      // meter, and the last one reads undefined. Same track/channel confusion
      // that channels.py exists to prevent, on the other side of the wire.
      for (const b of el.speakers.children) {
        const bar = b.querySelector('.meter i');
        if (!bar) continue;
        const ch = b.dataset.channel;
        const lvl = ch === undefined ? 0 : (levels[Number(ch) + this.offset()] || 0);
        bar.style.width = `${Math.min(100, lvl * 320)}%`;
      }
      requestAnimationFrame(tick);
    };
    requestAnimationFrame(tick);
  },
};

const fmt = (s) => {
  s = Math.max(0, s | 0);
  return `${(s / 60) | 0}:${String(s % 60).padStart(2, '0')}`;
};

