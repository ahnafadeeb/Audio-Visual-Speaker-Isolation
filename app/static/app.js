/* Audio-Visual Speaker Isolation — frontend.
 *
 * The whole design rests on one invariant: EXACTLY ONE AUDIO CLOCK.
 *
 * All speaker stems arrive as channels of a single multichannel WAV, decoded
 * into one AudioBuffer and played by one AudioBufferSourceNode, fanned out with
 * a ChannelSplitterNode into one GainNode per speaker. Because there is one
 * buffer and one source, the stems physically cannot drift relative to each
 * other. Only video-vs-audio needs correcting, and the video is the slave.
 *
 * Switching speakers is a gain automation on the audio thread — never a
 * re-decode, never a seek, never a source swap.
 */
'use strict';

const XFADE = 0.025;          // 25 ms crossfade
const CURVE_POINTS = 64;
// Correction deadband, applied to the drift AFTER frame quantisation has been
// removed (see transport.correct). 20 ms was wrong in an instructive way: it is
// exactly half a frame period at 25 fps, and a video frame is on screen at a
// frame boundary or not at all. So even with the clocks in perfect agreement,
// mediaTime - audioPos sweeps the whole 0..40 ms interval as playback advances
// between boundaries, and sits above 20 ms for 50% of that sweep. Simulated in
// scripts/check_transport.py: 50.0% of ticks read "warn" and wrote
// playbackRate, on a clip that was perfectly in sync. That is the yellow
// readout that was reported.
//
// Widening the band to a full frame period is NOT the fix, and the same script
// rejects it: quantisation is strictly one-sided (mediaTime is floored, so it
// can only lag), and a symmetric ±40 ms band would excuse 40 ms of genuine
// audio-ahead error to tolerate a lag that never exceeds 40 ms. Debias first,
// then keep the band tight. 20 ms of residual is one 60 Hz vsync of
// presentation lead that rVFC does not report.
const DEADBAND  = 0.020;
const MAX_RATE  = 0.02;       // ±2% playbackRate authority
const HARD_SEEK = 0.250;      // 250 ms — give up and reseek
const KP        = 0.5;

// How far ahead of ctx.currentTime a gain switch is scheduled. The render
// quantum is a fixed 128 FRAMES, which at our 16 kHz context is 8 ms — so
// currentTime advances in 8 ms steps and a 5 ms lead lands inside the block
// already being rendered. The spec then applies the event at the start of that
// block, truncating the head of the crossfade. 20 ms clears two quanta on every
// implementation while staying far below the ~100 ms that reads as "instant".
const SCHED_LEAD = 0.020;

// Cap the overlay's backing store at 2x. Below this the box strokes are blurry
// on a HiDPI laptop; above it the canvas costs memory for no visible gain.
const MAX_DPR = 2;

// Equal-power crossfade curves. up² + down² === 1 at every point, so total
// acoustic power is constant through the switch and there is no dip.
const UP   = new Float32Array(CURVE_POINTS);
const DOWN = new Float32Array(CURVE_POINTS);
for (let i = 0; i < CURVE_POINTS; i++) {
  const x = i / (CURVE_POINTS - 1);
  UP[i]   = Math.sin(x * Math.PI / 2);
  DOWN[i] = Math.cos(x * Math.PI / 2);
}

