async function upload(file) {
  showError(null);
  el.panelUpload.hidden = true;
  el.panelProgress.hidden = false;

  const fd = new FormData();
  fd.append('file', file);
  let res;
  try {
    res = await fetch('/api/jobs', { method: 'POST', body: fd });
  } catch (err) {
    // The server being down is the single most likely failure at a demo, and
    // an unhandled rejection here left the progress panel up at 0% with no
    // message — indistinguishable from a slow model load.
    toUpload(`cannot reach the server (${err.message})`);
    return;
  }
  if (!res.ok) {
    toUpload((await res.json().catch(() => ({}))).detail || `upload failed (${res.status})`);
    return;
  }
  const { job_id } = await res.json();
  listen(job_id);
}

/* Back to the upload panel with a message. Every failure path needs this, and
 * each one open-coding it is how one of them ends up forgetting to unhide the
 * panel — leaving a dead page with an error and no way to retry. */
function toUpload(message) {
  showError(message);
  el.panelProgress.hidden = true;
  el.panelPlayer.hidden = true;
  el.panelUpload.hidden = false;
}

function listen(jobId) {
  const es = new EventSource(`/api/jobs/${jobId}/events`);
  es.onmessage = async (e) => {
    let s;
    try {
      s = JSON.parse(e.data);
    } catch (err) {
      // Should be unreachable since serialization.dumps scrubs non-finite
      // floats (REVIEW_CONTRACTS F-1), but if it ever regresses the failure is
      // a silently frozen progress bar. Make it say so instead.
      es.close();
      toUpload(`malformed event from the server: ${err.message}`);
      return;
    }
    el.barFill.style.width = `${(s.pct * 100).toFixed(1)}%`;
    el.stage.textContent = s.stage;
    el.msg.textContent = s.message || '';
    if (s.state === 'done') {
      es.close();
      try {
        await load(jobId, s.meta);
      } catch (err) {
        // load() awaits four fetches and a decode. Any of them rejecting used
        // to surface as an unhandled promise rejection inside an event handler
        // — console-only, with the progress bar sitting at 100% forever.
        toUpload(`could not load the finished job: ${err.message}`);
      }
    }
    if (s.state === 'error') { es.close(); toUpload(s.error); }
  };
  es.onerror = () => { es.close(); toUpload('lost connection to the server'); };
}

async function load(jobId, meta) {
  const base = `/api/jobs/${jobId}/artifact`;
  // Retire the running correction loop and reset the transport BEFORE either
  // media element is swapped, so a second job cannot inherit the first one's
  // Play/Pause label, drift readout, or a loop still writing playbackRate.
  transport.gen++;
  el.playpause.textContent = 'Play';
  el.drift.textContent = '';
  el.drift.className = 'drift';

  el.video.src = `${base}/video.mp4`;      // start the download in parallel
  // Channel count comes back from init(); writeDiag() reads it off the graph
  // rather than from a local, so there is one place it can be wrong.
  await engine.init(`${base}/stems_demo.wav`);

  const tr = await fetch(`${base}/tracks.json`);
  if (!tr.ok) throw new Error(`tracks.json (${tr.status})`);
  const tracks = await tr.json();

  ui.setTracks(tracks, meta);
  el.panelProgress.hidden = true;
  el.panelPlayer.hidden = false;

  ui.writeDiag();
  ui.updateTime(0);
  ui.draw(0);
  ui.meters();
}

function showError(m) {
  el.error.hidden = !m;
  el.error.textContent = m || '';
}

/* Leave the player for the upload panel. Without this the only way to a
 * second video was reloading the page -- and after a /?job= deep link, even a
 * reload came straight back to the same job. Playback is stopped first so the
 * old job's audio cannot keep sounding under the upload panel, and the
 * generation token retires its correction loop. */
function newVideo() {
  if (engine.playing) engine.pause();
  engine.pausedAt = 0;
  el.video.pause();
  el.video.removeAttribute('src');
  el.video.load();
  transport.gen++;
  el.playpause.textContent = 'Play';
  if (new URLSearchParams(location.search).has('job')) {
    history.replaceState(null, '', location.pathname);
  }
  toUpload(null);
}

